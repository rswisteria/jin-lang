def test_completion_survives_a_syntax_error_in_the_expression_being_typed() -> None:
    """打鍵途中の式（JIN201）でも、そのステップのスコープで候補を出す。"""
    broken = PADDLE.replace('"expr": "ball.x + ball.vx * dt"', '"expr": "ball.x +"', 1)
    state = DocumentStore().update(URI, broken)
    assert any(d.code == "JIN201" for d in state.diagnostics)
    line = next(i for i, l in enumerate(broken.splitlines()) if '"expr": "ball.x +"' in l)
    column = broken.splitlines()[line].index('"ball.x') + 1
    found = labels(state, types.Position(line=line, character=column))
    assert found[:2] == ["dt", "ball"]


