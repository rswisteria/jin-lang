# ---------------------------------------------------------------- jin/applyOps（v2）


def test_apply_ops_applies_a_v2_operation_and_returns_its_inverse_and_jil(state) -> None:
    op = {
        "op": "addState",
        "pointer": "/circles/1/state",
        "value": {"name": "lives", "type": "num", "init": "3"},
    }
    result = requests.jin_apply_ops(state, URI, [op])
    assert result["ok"] is True
    assert result["inverses"] == [{"op": "removeState", "pointer": "/circles/1/state/3"}]
    assert result["warnings"] == []
    assert result["model"]["circles"][1]["state"][3]["name"] == "lives"
    # テキストは正準形（保存と `jin fmt` がバイト一致する・要件書 成功条件 5）
    assert result["text"] == dumps(JinFileV2.model_validate(result["model"]))
    assert check_text(result["text"], "m.jin").ok
    # ライブリロード用の JIL（addState は生成部に現れる）
    assert result["jilError"] is None and '"lives"' in result["jil"]


def test_apply_ops_keeps_ok_when_the_expression_is_broken_but_reports_no_jil(state) -> None:
    """ops.md §1: 式の構文 / 型エラーはオペレーションの失敗にしない。JIL だけが作れない。"""
    op = {"op": "setStep", "pointer": "/circles/1/rites/0/steps/0", "value": {"expr": "nope +"}}
    result = requests.jin_apply_ops(state, URI, [op])
    assert result["ok"] is True
    assert result["jil"] is None and result["manifest"] is None
    assert "JIN201" in result["jilError"]


def test_apply_ops_reports_a_v2_failure_with_a_code(state) -> None:
    result = requests.jin_apply_ops(state, URI, [{"op": "removeCircle", "pointer": "/circles/9"}])
    assert result["ok"] is False
    assert result["error"]["code"] == "JIN002"
    assert result["error"]["pointer"] == "/circles/9"


@pytest.mark.parametrize("name", sorted(OPERATIONS))
def test_every_v2_operation_name_is_reachable_through_apply_ops(state, name: str) -> None:
    """未知のオペレーションと同じ経路（JIN002・`未知のオペレーション`）に落ちないこと。

    引数不足で失敗してもよい（それは各オペレーションの検査）。32 件が `jin_core.v2.ops.OPERATIONS`
    経由で呼ばれていることだけを見る。
    """
    result = requests.jin_apply_ops(state, URI, [{"op": name, "pointer": "/nope"}])
    assert result["ok"] is False
    assert "未知のオペレーション" not in result["error"]["message"]


def test_apply_ops_matches_jin_core_v2_ops_byte_for_byte(state) -> None:
    ops = [
        {"op": "rename", "pointer": "/circles/1/state/2", "value": "points"},
        {"op": "addStep", "pointer": "/circles/1/rites/0/steps", "value": {"do": "finish"}},
    ]
    result = requests.jin_apply_ops(state, URI, ops)
    expected = apply_ops(state.model, ops)
    assert result["text"] == dumps(expected.model)
    assert result["inverses"] == expected.inverses


