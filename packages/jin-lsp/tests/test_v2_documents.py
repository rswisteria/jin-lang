from jin_lsp import requests
from jin_lsp.features import completion, edits, navigation
from jin_lsp.session import DocumentStore
from lsprotocol import types

REPO_ROOT = Path(__file__).resolve().parents[3]
PADDLE = (REPO_ROOT / "examples-v2" / "paddle" / "paddle.jin").read_text(encoding="utf-8")
URI = "file:///paddle.jin"


@pytest.fixture
def state():
    store = DocumentStore()
    return store.update(URI, PADDLE)


def position_of(needle: str, inside: str, offset: int = 1) -> types.Position:
    """`needle` を含む最初の行の、`inside` の先頭から `offset` 文字目（LSP の 0 始まり）。"""
    for index, line in enumerate(PADDLE.splitlines()):
        if needle in line:
            return types.Position(line=index, character=line.index(inside) + offset)
    raise AssertionError(f"{needle!r} を含む行が無い")


def labels(state, position: types.Position) -> list[str]:
    return [item.label for item in completion.complete(state, position).items]


def hover_text(state, position: types.Position) -> str:
    found = navigation.hover(state, position)
    assert found is not None
    return found.contents.value


