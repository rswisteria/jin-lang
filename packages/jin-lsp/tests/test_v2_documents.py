def test_completion_in_an_expression_lists_identifiers_in_scope_order(state) -> None:
    found = labels(state, position_of('"expr": "ball.x + ball.vx * dt"', '"ball.x'))
    # 局所 → state → sigil（点付き）→ 他の陣の公開 state（点付き）→ 型紙 → 純関数
    assert found.index("dt") < found.index("ball") < found.index("input.key")
    assert found.index("input.key") < found.index("Result.quit") < found.index("Ball")
    assert found.index("Ball") < found.index("abs")
    assert "canvas.rect" not in found  # 戻り値の無いメンバは式に書けない（expr.md §3.3）


