"""codegen（v2 → JIL）: スナップショット・examples の実行・決定性・fixture の意味論。

スナップショットは `__snapshots__/test_codegen.ambr`（syrupy）。生成部の形を変えたら
`uv run pytest packages/jin-wasm --snapshot-update` で更新し、**差分を読んでから**コミットする。
プレリュードは別ファイル（`prelude.lua`）なのでスナップショットには生成部だけを載せる。
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

import pytest
from jin_core.check import check_file, check_text
from jin_core.v2.model import JinFileV2
from jin_wasm.codegen import CodegenError, generate, lua_number, lua_string
from jin_wasm.jil import JIL_VERSION, forbidden_uses
from jin_wasm.prelude import prelude_source
from jin_wasm.runtime import HeadlessResult, run_headless

REPO_ROOT = Path(__file__).resolve().parents[3]
EXAMPLES = REPO_ROOT / "examples-v2"
PROGRAMS = REPO_ROOT / "tests" / "fixtures" / "v2-programs"
EXAMPLE_NAMES = ("paddle", "clicker", "fib")


def load(path: Path) -> JinFileV2:
    result = check_file(path)
    assert result.ok, [d.message for d in result.diagnostics]
    assert isinstance(result.model, JinFileV2)
    return result.model


def program_part(lua: str) -> str:
    return lua.split("\n-- program\n", 1)[1]


def run(
    name: str, *, debug: bool = True, ticks: int = 300, seed: int = 7, events=()
) -> HeadlessResult:
    path = PROGRAMS / f"{name}.jin"
    game = generate(load(path), source_name=path.name, debug=debug)
    assert forbidden_uses(game.lua) == []
    return run_headless(game.lua, game.manifest, seed=seed, ticks=ticks, events=events)


def public_series(result: HeadlessResult, key: str) -> list:
    return [
        r["output"]
        for r in result.rows
        if r["kind"] == "set"
        and r["name"] == key.split(".")[1]
        and r["circle"] == key.split(".")[0]
    ]


