# ---------------------------------------------------------------- num は常に float（jil.md §2）


@pytest.mark.parametrize("name", ["each_list", "wait_until", "key_pointer"])
def test_num_states_are_floats_at_runtime(name: str) -> None:
    """生成部の数値リテラル・純関数・添字計算が整数サブタイプを作らないことを、実行後の state で見る。

    文字列の走査では陣の添字（`STOP(2)` など）と区別できないので、`S[i]` を返す末尾を足して
    `math.type` を読む（テスト専用の JIL。`jin build` の出力ではない）。
    """
    from jin_wasm.runtime import sandboxed_runtime

    path = PROGRAMS / f"{name}.jin"
    model = load(path)
    game = generate(model, source_name=path.name, debug=False)
    lua = game.lua.replace(
        "return { boot = boot, tick = tick }\n", "return { boot = boot, tick = tick, S = S }\n"
    )
    runtime, arm = sandboxed_runtime()
    arm(10_000_000)
    entry = runtime.execute(lua)
    entry.boot(0, runtime.table_from(game.manifest, recursive=True))
    for t in range(4):
        entry.tick(
            t,
            runtime.table_from(
                {"events": [], "keys": {}, "pointer": {"x": 0.0, "y": 0.0, "down": False}},
                recursive=True,
            ),
        )
    math_type = runtime.eval("math.type")
    checked = 0
    for i, circle in enumerate(model.circles, start=1):
        for j, state in enumerate(circle.state):
            if state.type != "num":
                continue
            value = entry.S[i][f"k_{j}"]
            assert math_type(value) == "float", (circle.name, state.name, value)
            checked += 1
    assert checked >= 1
