def test_parallel_children_read_the_previous_ticks_published_value() -> None:
    result = run("parallel_order", ticks=5)
    assert public_series(result, "A.seenB") == [0, 1, 2, 3, 4]
    assert public_series(result, "B.seenA") == [0, 1, 2, 3, 4]
    assert result.public == {"A.a": 5, "A.seenB": 4, "B.b": 5, "B.seenA": 4}


def test_parallel_order_does_not_change_the_public_series() -> None:
    path = PROGRAMS / "parallel_order.jin"
    doc = json.loads(path.read_text(encoding="utf-8"))
    swapped = copy.deepcopy(doc)
    swapped["circles"][0]["flow"]["steps"] = ["B", "A"]
    original = check_text(json.dumps(doc), "a.jin").model
    reordered = check_text(json.dumps(swapped), "b.jin").model
    a = run_headless(*_game(original, True), seed=1, ticks=6)
    b = run_headless(*_game(reordered, True), seed=1, ticks=6)
    for key in ("A.a", "A.seenB", "B.b", "B.seenA"):
        assert public_series(a, key) == public_series(b, key), key
    assert a.public == b.public


def test_transfer_pauses_the_delegator_until_the_delegate_is_done() -> None:
    result = run("transfer", ticks=6)
    assert result.error is None
    assert result.public == {"Main.n": 4, "Sub.m": 2}
    kinds = [
        (r["tick"], r["kind"], r["circle"])
        for r in result.rows
        if r["kind"] in ("transfer", "enter", "exit")
    ]
    assert kinds == [
        (-1, "enter", "Main"),
        (1, "transfer", "Main"),
        (1, "enter", "Sub"),
        (3, "exit", "Sub"),
    ]
    # Main は tick 2 / 3 の間 tick を受けない
    main_ticks = [r["tick"] for r in result.rows if r["kind"] == "event" and r["circle"] == "Main"]
    assert main_ticks == [0, 1, 4, 5]


def test_emit_is_delivered_on_the_next_tick() -> None:
    result = run("emit_message", ticks=3)
    assert result.public == {"Receiver.got": 42, "Receiver.text": "hi"}
    emit = next(r for r in result.rows if r["kind"] == "emit")
    assert (
        emit["tick"] == 1 and emit["input"] == [42, "hi"] and emit["output"] is True
    )  # 配達の tick に積む
    event = next(r for r in result.rows if r["kind"] == "event" and r["name"] == "message")
    assert event["tick"] == 1 and event["input"] == ["hello", 42, "hi"]
    got = next(r for r in result.rows if r["kind"] == "set" and r["name"] == "got")
    assert got["tick"] == 1


