@pytest.mark.parametrize("name", EXAMPLE_NAMES)
def test_examples_run_300_ticks_without_error(name: str) -> None:
    path = EXAMPLES / name / f"{name}.jin"
    for debug in (True, False):
        game = generate(load(path), source_name=path.name, debug=debug)
        assert forbidden_uses(game.lua) == []
        result = run_headless(game.lua, game.manifest, seed=7, ticks=300)
        assert result.error is None
        assert all(
            list(r) == ["seq", "tick", "circle", "kind", "name", "pointer", "input", "output"]
            for r in result.rows
        )


@pytest.mark.parametrize("name", EXAMPLE_NAMES)
def test_debug_and_release_produce_the_same_frames(name: str) -> None:
    path = EXAMPLES / name / f"{name}.jin"
    model = load(path)
    debug = run_headless(*_game(model, True), seed=7, ticks=120)
    release = run_headless(*_game(model, False), seed=7, ticks=120)
    assert release.rows == []
    assert json.dumps(release.frames) == json.dumps(debug.frames)
    assert release.public == debug.public


@pytest.mark.parametrize("name", EXAMPLE_NAMES)
def test_two_runs_are_byte_identical(name: str) -> None:
    path = EXAMPLES / name / f"{name}.jin"
    model = load(path)
    a = run_headless(*_game(model, True), seed=7, ticks=120)
    b = run_headless(*_game(model, True), seed=7, ticks=120)
    assert json.dumps(a.rows) == json.dumps(b.rows)
    assert json.dumps(a.frames) == json.dumps(b.frames)


def _game(model: JinFileV2, debug: bool):
    game = generate(model, source_name="x.jin", debug=debug)
    return game.lua, game.manifest


