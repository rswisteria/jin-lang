def glyph_d(gid: str, x: float, y: float, size: float) -> str:
    """字形を左上 (x, y)・一辺 size の升に写した `d`。数値はすべて `fmt_coord` を通す。"""
    scale = size / 100.0
    parts: list[str] = []
    for op, nums in GLYPH_PATHS[gid]:
        coords = [fmt_coord((x if i % 2 == 0 else y) + v * scale) for i, v in enumerate(nums)]
        parts.append(op + " ".join(coords) if coords else op)
    return " ".join(parts)


