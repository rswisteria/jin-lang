def _data_segments(wat: str) -> dict[int, bytes]:
    out: dict[int, bytes] = {}
    for m in re.finditer(r'\(data \(i32\.const (\d+)\) "((?:[^"\\]|\\.)*)"\)', wat):
        text = m.group(2)
        raw = bytearray()
        i = 0
        while i < len(text):
            if text[i] == "\\":
                if text[i + 1] in ("\\", '"'):
                    raw.append(ord(text[i + 1]))
                    i += 2
                else:
                    raw.append(int(text[i + 1 : i + 3], 16))
                    i += 3
            else:
                raw.append(ord(text[i]))
                i += 1
        out[int(m.group(1))] = bytes(raw)
    return out


def test_runtime_strings_stay_below_the_program_data_base() -> None:
    """`runtime.wat` の文字列は [0, DATA_BASE) に閉じ、`$puts` / `$mem_str` などの (番地, 長さ) は実在の文字列を指す。"""
    source = runtime_source()
    segments = _data_segments(source)
    assert segments, "runtime.wat の data 区画が読めない"
    assert min(segments) == 0
    assert max(off + len(raw) for off, raw in segments.items()) <= DATA_BASE
    for expected in (b"NaN", b"Infinity", b"true", b"false", b"null", b'{"ops":[', b'],"audio":['):
        assert expected in segments.values(), expected
    # 番地 + 長さの組はすべて data 区画の文字列（生成器が振った番地が、生成物の中で辻褄が合っている）
    pairs = re.findall(
        r"\(call \$(?:puts|mem_str) \(i32\.const (\d+)\) \(i32\.const (\d+)\)\)", source
    )
    pairs += re.findall(
        r"\$(?:str_eq_mem|j_getk) [^\n]*? \(i32\.const (\d+)\) \(i32\.const (\d+)\)\)", source
    )
    assert len(pairs) > 40
    for off, length in pairs:
        assert segments.get(int(off)) is not None and len(segments[int(off)]) == int(length), (
            off,
            length,
        )
    assert "$put_jn" in source  # 生成部の pub_i が呼ぶ JSON の数値（JN 相当）


def test_runtime_wat_is_generated_from_its_parts() -> None:
    """`runtime.wat` は `scripts/generate_runtime_wat.py` の生成物（手で編集しない）。CI の diff と 2 重の網。"""
    import subprocess
    import sys

    repo = Path(__file__).resolve().parents[3]
    check = subprocess.run(
        [sys.executable, str(repo / "scripts" / "generate_runtime_wat.py"), "--check"],
        capture_output=True,
        text=True,
        check=False,
    )
    assert check.returncode == 0, check.stdout + check.stderr
    assert "scripts/generate_runtime_wat.py" in runtime_source()
    # 生成器の DATA_BASE は codegen.DATA_BASE と手で揃えた重複（生成器は jin_wasmgc を import しない）
    script = (repo / "scripts" / "generate_runtime_wat.py").read_text(encoding="utf-8")
    assert f"DATA_BASE = {DATA_BASE}\n" in script
    assert (repo / "packages" / "jin-wasmgc" / "runtime" / "strings.json").is_file()
    ci = (repo / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
    assert (
        "uv run python scripts/generate_runtime_wat.py --stdout "
        "| diff -u packages/jin-wasmgc/src/jin_wasmgc/runtime.wat -"
    ) in ci


def test_program_data_starts_at_the_base_and_the_input_area_follows() -> None:
    program = generate_program(load(FIB))
    segments = _data_segments(program)
    assert min(segments) == DATA_BASE
    assert b'"Fib.answer":' in segments.values()
    in_base = int(re.search(r"\(global \$in_base i32 \(i32\.const (\d+)\)\)", program).group(1))
    assert in_base % 16 == 0 and in_base >= max(o + len(r) for o, r in segments.items())


def test_string_literals_are_passive_data_created_with_array_new_data() -> None:
    state = [{"name": "s", "type": "str", "init": '"日本 \\"q\\""', "out": True}]
    program = generate_program(model_from(doc(circle("T", state, [{"name": "main", "steps": []}]))))
    assert '(data $L0 "\\e6\\97\\a5\\e6\\9c\\ac \\22q\\22")' in program
    assert "(array.new_data $str $L0 (i32.const 0) (i32.const 10))" in program


# ---------------------------------------------------------------- 名前を識別子に埋めない（jil.md §6.3）


def test_names_appear_only_in_the_data_section() -> None:
    program = generate_program(load(FIB))
    code = re.sub(r";;.*", "", program)  # コメントは名前を含んでよい
    code = re.sub(r'\(data \(i32\.const \d+\) "[^"]*"\)', "", code)
    assert "Fib" not in code and "answer" not in code and "fib" not in code
    assert "$S0" in program and "$r0_0" in program and "$l0" in program


