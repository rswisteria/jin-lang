FIB = EXAMPLES / "fib" / "fib.jin"


def load(path: Path) -> JinFileV2:
    result = check_file(path)
    assert result.ok, [d.message for d in result.diagnostics]
    assert isinstance(result.model, JinFileV2)
    return result.model


def model_from(doc: dict) -> JinFileV2:
    result = check_text(json.dumps(doc), "t.jin")
    assert result.ok, [d.message for d in result.diagnostics]
    assert isinstance(result.model, JinFileV2)
    return result.model


def circle(name: str, state: list[dict], rites: list[dict], **extra) -> dict:
    return {"name": name, "core": "main", "state": state, "rites": rites, **extra}


def doc(*circles: dict, root: str = "T") -> dict:
    return {
        "$schema": "https://xtone.internal/jin/schemas/jin-v2.schema.json",
        "version": 2,
        "root": root,
        "stage": {"width": 64, "height": 64},
        "circles": list(circles),
    }


