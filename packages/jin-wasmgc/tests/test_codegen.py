def test_two_assemblies_are_byte_identical() -> None:
    a = assemble(load(FIB), source_name="fib.jin")
    b = assemble(load(FIB), source_name="fib.jin")
    assert a.wasm == b.wasm and a.manifest == b.manifest
    assert isinstance(a.wasm, bytes)


def test_header_names_the_shared_jil_version() -> None:
    game = assemble(load(FIB), source_name="fib.jin")
    lines = game.wat.splitlines()
    assert lines[0] == ";; generated by jin — do not edit"
    assert lines[1] == ';; source: "fib.jin"'
    assert lines[2] == f";; jin: 2  jil: {JIL_VERSION}  target: wasm-gc"


def test_a_control_character_in_the_source_name_cannot_escape_the_comment() -> None:
    game = assemble(load(FIB), source_name="a\nb.jin")
    assert game.wat.splitlines()[1] == ';; source: "a\\010b.jin"'


def test_manifest_shares_the_common_part_and_names_the_target() -> None:
    from jin_wasm.codegen import generate as generate_lua

    wasm = assemble(load(FIB), source_name="fib.jin")
    lua = generate_lua(load(FIB), source_name="fib.jin")
    common = {k: v for k, v in lua.manifest.items() if k != "jil"}
    assert {k: v for k, v in wasm.manifest.items() if k not in ("target", "wasm")} == common
    assert wasm.manifest["target"] == TARGET == "wasm-gc"
    assert re.fullmatch(r"[0-9a-f]{64}", wasm.manifest["wasm"])
    assert "jil" not in wasm.manifest
    assert list(wasm.manifest) == [*common, "target", "wasm"]
    assert GAME_WASM == "game.wasm"


