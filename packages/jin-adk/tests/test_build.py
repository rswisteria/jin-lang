def test_force_does_not_truncate_existing_files_when_a_later_file_is_refused(
    tmp_path: Path,
) -> None:
    """`--force` で 3 つ目（`.env.example` がリンク）に拒まれても、前の 2 つは open 時点で切り詰められない。

    `O_TRUNC` で開くと open した瞬間に中身が消え、拒否後に 0 バイトのファイルが残る（Phase 1 の V-1 と同型）。
    一時ファイル（`.<name>.jin-tmp`）も残さない。
    """
    out = tmp_path / "out"
    write_project(project(), out)
    init_before = (out / "Researcher" / "__init__.py").read_bytes()
    agent_before = (out / "Researcher" / "agent.py").read_bytes()
    victim = tmp_path / "victim"
    victim.write_text("keep\n", encoding="utf-8")
    (out / ".env.example").unlink()
    (out / ".env.example").symlink_to(victim)
    with pytest.raises(WriteRefused):
        write_project(project(), out, force=True)
    assert (out / "Researcher" / "__init__.py").read_bytes() == init_before
    assert (out / "Researcher" / "agent.py").read_bytes() == agent_before
    assert victim.read_text(encoding="utf-8") == "keep\n"
    assert not list(out.rglob(f"*{TMP_SUFFIX}"))


def test_force_write_failure_keeps_the_existing_files_intact(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """F-S-P2-104: `--force` で 2 回目の `os.write` が ENOSPC で失敗しても、既存 3 ファイルは 1 バイトも変わらない。

    `ftruncate` してから書く方式では `agent.py` が 0 バイトで残った（reviewer の実測）。
    一時ファイルに書いて `os.replace` で差し替えるので、書き込みの失敗は既存に届かない。残骸も残さない。
    """
    out = tmp_path / "out"
    write_project(project(), out)
    files = [
        out / "Researcher" / "__init__.py",
        out / "Researcher" / "agent.py",
        out / ".env.example",
    ]
    for path in files:
        # 再生成と同じ内容だと「差し替えられた」ことが見えない（変異 BUILD-replace-early が緑のままだった）
        path.write_text("hand edited\n", encoding="utf-8")
    before = {path: path.read_bytes() for path in files}
    calls = 0
    real_write = os.write

    def flaky(fd: int, data: object) -> int:
        nonlocal calls
        calls += 1
        if calls == 2:
            raise OSError(28, "No space left on device")
        return real_write(fd, data)  # type: ignore[arg-type]

    monkeypatch.setattr(os, "write", flaky)
    with pytest.raises(WriteRefused) as info:
        write_project(project(), out, force=True)
    assert "No space left" in str(info.value)
    for path, content in before.items():
        assert path.read_bytes() == content, path
    assert not list(out.rglob(f"*{TMP_SUFFIX}"))


def test_force_succeeds_by_replacing_through_a_temporary_file(tmp_path: Path) -> None:
    """`--force` の正常系: 一時ファイルは差し替えられて残らず、3 ファイルとも新しい内容になる。"""
    out = tmp_path / "out"
    write_project(project(), out)
    for path in (out / "Researcher" / "agent.py", out / ".env.example"):
        path.write_text("hand edited\n", encoding="utf-8")
    written = write_project(project(), out, force=True)
    assert len(written) == 3
    assert "hand edited" not in (out / "Researcher" / "agent.py").read_text(encoding="utf-8")
    assert "hand edited" not in (out / ".env.example").read_text(encoding="utf-8")
    assert not list(out.rglob(f"*{TMP_SUFFIX}"))


def test_force_keeps_the_existing_file_mode_F_S_P2_204_F_C_P2_201(tmp_path: Path) -> None:
    """F-S-P2-204 = F-C-P2-201: `--force` の差し替えは既存ファイルのモードを引き継ぐ
    （利用者が `chmod 600` した `agent.py` を umask の既定 0644 に戻さない。旧 `ftruncate` 方式と同じ挙動）。"""
    out = tmp_path / "out"
    write_project(project(), out)
    agent = out / "Researcher" / "agent.py"
    agent.chmod(0o600)
    (out / ".env.example").chmod(0o640)
    write_project(project(), out, force=True)
    assert stat.S_IMODE(agent.stat().st_mode) == 0o600
    assert stat.S_IMODE((out / ".env.example").stat().st_mode) == 0o640


def test_fchmod_failure_on_the_temporary_file_leaves_no_leftover(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """F-S-P2-301（ラウンド 3 の F-S-P2-204 修正が持ち込んだ）: tmp への `os.fchmod` が失敗しても
    `.<name>.jin-tmp` と fd を残さず `WriteRefused` にする（次の `--force` が「残骸」で拒まれない）。既存は無傷。"""
    out = tmp_path / "out"
    write_project(project(), out)
    before = {p: p.read_bytes() for p in out.rglob("*") if p.is_file()}

    def denied(fd: int, mode: int) -> None:
        raise PermissionError(1, "Operation not permitted")

    monkeypatch.setattr(os, "fchmod", denied)
    with pytest.raises(WriteRefused) as info:
        write_project(project(), out, force=True)
    assert "引き継げません" in str(info.value)
    assert not list(out.rglob(f"*{TMP_SUFFIX}")), "一時ファイルの残骸が残っている"
    for path, content in before.items():
        assert path.read_bytes() == content, path
    monkeypatch.undo()
    write_project(project(), out, force=True)  # 残骸が無いので次の --force は通る


def test_partial_apply_on_replace_failure_is_named_in_the_message(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """F-S-P2-203: 3 つ目の `os.replace` が失敗すると部分適用になる（原子性は追求しない）。
    どれが新しくどれが前のままかを文で言い、`jin build --force` の再実行を促す。`agent.py` は最後に差し替える。"""
    out = tmp_path / "out"
    write_project(project(), out)
    for path in (
        out / "Researcher" / "agent.py",
        out / "Researcher" / "__init__.py",
        out / ".env.example",
    ):
        path.write_text("old\n", encoding="utf-8")
    calls = 0
    real_replace = os.replace

    def flaky(*args, **kwargs):
        nonlocal calls
        calls += 1
        if calls == 3:
            raise PermissionError(13, "Permission denied")
        return real_replace(*args, **kwargs)

    monkeypatch.setattr(os, "replace", flaky)
    with pytest.raises(WriteRefused) as info:
        write_project(project(), out, force=True)
    message = str(info.value)
    assert "部分適用" in message and "jin build --force" in message
    assert "agent.py は前の内容のまま" in message
    # agent.py は最後なので前のまま、先の 2 つは新しい
    assert (out / "Researcher" / "agent.py").read_text(encoding="utf-8") == "old\n"
    assert (out / ".env.example").read_text(encoding="utf-8") != "old\n"
    assert not list(out.rglob(f"*{TMP_SUFFIX}"))


def test_leftover_temporary_file_is_refused_not_overwritten(tmp_path: Path) -> None:
    """前回の残骸 `.agent.py.jin-tmp` があれば `--force` でも拒む（黙って上書きしない）。"""
    out = tmp_path / "out"
    write_project(project(), out)
    leftover = out / "Researcher" / f".agent.py{TMP_SUFFIX}"
    leftover.write_text("leftover\n", encoding="utf-8")
    with pytest.raises(WriteRefused) as info:
        write_project(project(), out, force=True)
    assert "残っています" in str(info.value)
    assert leftover.read_text(encoding="utf-8") == "leftover\n"


