def test_unencodable_content_is_refused_before_any_file_is_touched(tmp_path: Path) -> None:
    """F-S-P2-005: 孤立サロゲート（不正 UTF-8 のファイル名由来）は encode を **open より前**に済ませて拒む。
    `--force` でも既存の生成物は 1 バイトも変わらず、新規なら 0 バイトのファイルを残さない。"""
    out = tmp_path / "out"
    with pytest.raises(WriteRefused) as info:
        write_project(forged(agent_py="# bad \udcff\n"), out)
    assert "UTF-8" in str(info.value)
    assert not (out / "Researcher").exists() and not (out / ".env.example").exists()

    write_project(project(), out)
    before = (out / "Researcher" / "agent.py").read_bytes()
    with pytest.raises(WriteRefused):
        write_project(forged(agent_py="# bad \udcff\n"), out, force=True)
    assert (out / "Researcher" / "agent.py").read_bytes() == before


def test_write_failure_after_open_cleans_up_only_what_it_created(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """F-C-P2-020: `os.write` の失敗（ENOSPC 等）でも作りかけを残さない（`WriteRefused` 以外の経路）。"""
    out = tmp_path / "out"

    def full_disk(fd: int, data: object) -> int:
        raise OSError(28, "No space left on device")

    monkeypatch.setattr(os, "write", full_disk)
    with pytest.raises(WriteRefused) as info:
        write_project(project(), out)
    assert "No space left" in str(info.value)
    assert not (out / "Researcher").exists() and not (out / ".env.example").exists()


