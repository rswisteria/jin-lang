def test_refuses_when_the_package_directory_is_a_symlink(tmp_path: Path) -> None:
    """`<out>/<root_name>` がリンクなら、その先（`<out>` の外）へ書き抜けてしまう。"""
    out = tmp_path / "out"
    elsewhere = tmp_path / "elsewhere"
    out.mkdir()
