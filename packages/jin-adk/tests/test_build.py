def test_model_with_invalid_structure_is_not_written(tmp_path: Path) -> None:
    """generate が BuildError を出す入力は、ファイルを 1 つも作らない（呼び出し側の責務も含めて確認）。"""
    from jin_adk.codegen import BuildError

    model = JinFile.model_validate(
        {
            "$schema": "https://xtone.internal/jin/schemas/jin.schema.json",
            "version": 1,
            "root": "class",
            "circles": [{"name": "class", "core": "m"}],
        }
    )
    with pytest.raises(BuildError):
        generate(model)
    assert not (tmp_path / "class").exists()
