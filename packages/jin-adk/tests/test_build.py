"""`jin_adk.build.write_project`: 生成物を `<out>/<root_name>/` へ安全に書き出す。

design.yaml Phase 2 machine 条件 3（ディレクトリ構造が要件書 §3.1 と一致）と、
security: 既存ファイルを黙って上書きしない / `<out>` の外へ書かない / シンボリックリンクを辿らない。
"""

from __future__ import annotations

import os
import stat
from pathlib import Path

import pytest
from jin_adk.build import TMP_SUFFIX, WriteRefused, write_project
from jin_adk.codegen import GeneratedProject, generate
from jin_core.check import check_file
from jin_core.model import JinFile

REPO_ROOT = Path(__file__).resolve().parents[3]
EXAMPLES = REPO_ROOT / "examples"


def project(name: str = "researcher") -> GeneratedProject:
    result = check_file(EXAMPLES / name / f"{name}.jin")
    assert result.model is not None
    return generate(result.model, source_name=f"{name}.jin")


def test_layout_matches_requirements_section_3_1(tmp_path: Path) -> None:
    out = tmp_path / "out"
    written = write_project(project(), out)
    assert sorted(p.relative_to(out).as_posix() for p in written) == [
        ".env.example",
        "Researcher/__init__.py",
        "Researcher/agent.py",
    ]
    assert (
        (out / "Researcher" / "__init__.py")
        .read_text(encoding="utf-8")
        .startswith("# generated by jin")
    )
    assert "root_agent" in (out / "Researcher" / "agent.py").read_text(encoding="utf-8")
    assert "GOOGLE_API_KEY" in (out / ".env.example").read_text(encoding="utf-8")


def test_written_files_keep_lf_and_follow_the_umask(tmp_path: Path) -> None:
    out = tmp_path / "out"
    write_project(project("pipeline"), out)
    raw = (out / "Pipeline" / "agent.py").read_bytes()
    assert b"\r\n" not in raw
    current_umask = os.umask(0)
    os.umask(current_umask)
    mode = stat.S_IMODE((out / "Pipeline" / "agent.py").stat().st_mode)
    assert mode == 0o644 & ~current_umask


def test_refuses_to_overwrite_existing_files_without_force(tmp_path: Path) -> None:
    out = tmp_path / "out"
    write_project(project(), out)
    (out / "Researcher" / "agent.py").write_text("hand edited\n", encoding="utf-8")
    with pytest.raises(WriteRefused) as info:
        write_project(project(), out)
    assert "--force" in str(info.value)
    assert (out / "Researcher" / "agent.py").read_text(encoding="utf-8") == "hand edited\n"


def test_refuses_when_only_env_example_exists_and_leaves_nothing_behind(tmp_path: Path) -> None:
    """パッケージディレクトリが無くても `<out>/.env.example` が既存なら拒む（ファイル単位の O_EXCL）。

    拒んだときは、今作ったパッケージディレクトリと開きかけのファイルを残さない。
    """
    out = tmp_path / "out"
    out.mkdir()
    (out / ".env.example").write_text("GOOGLE_API_KEY=mine\n", encoding="utf-8")
    with pytest.raises(WriteRefused) as info:
        write_project(project(), out)
    assert ".env.example" in str(info.value) and "--force" in str(info.value)
    assert (out / ".env.example").read_text(encoding="utf-8") == "GOOGLE_API_KEY=mine\n"
    assert not (out / "Researcher").exists()
    assert sorted(p.name for p in out.iterdir()) == [".env.example"]


