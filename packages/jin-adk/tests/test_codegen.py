def _free_names(node: ast.AST) -> set[str]:
    """関数 / クラスの中で参照される名前のうち、その中で束縛されない（外側に解決される）もの。"""
    bound: set[str] = set()
    loads: set[str] = set()
    for sub in ast.walk(node):
        if isinstance(sub, ast.Name):
            (loads if isinstance(sub.ctx, ast.Load) else bound).add(sub.id)
        elif isinstance(sub, ast.arg):
            bound.add(sub.arg)
        elif isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            bound.add(sub.name)
    return loads - bound


def test_reserved_names_cover_every_free_name_the_template_uses() -> None:
    """F-S-P2-103: テンプレート由来の関数 / クラスが外側に解決する名前（組み込み名を含む）は
    すべて `RESERVED_NAMES` にある。列挙を手で保つのではなく、生成物の AST から機械で突き合わせる。
    対象は `has_exit` のときだけ描画される `_state_matches` / `StateCheckAgent`（pipeline は loop の exit を持つ）。
    """
    code = generate(load(EXAMPLES / "pipeline" / "pipeline.jin")).agent_py
    free: set[str] = set()
    definitions = [
        n for n in ast.parse(code).body if isinstance(n, (ast.FunctionDef, ast.ClassDef))
    ]
    assert {n.name for n in definitions} == {"_state_matches", "StateCheckAgent"}
    for node in definitions:
        free |= _free_names(node)
    assert {"isinstance", "str", "ValueError", "json", "BaseAgent"} <= free  # 検査が空でない
    assert free <= RESERVED_NAMES, f"RESERVED_NAMES に無い名前: {sorted(free - RESERVED_NAMES)}"


