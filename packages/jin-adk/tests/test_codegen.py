def test_generated_assignments_bind_each_name_exactly_once() -> None:
    """NFKC で同じ変数に 2 回代入される形（`root_agent` の乗っ取り）が生成物に現れない。"""
    for name in ("researcher", "pipeline"):
        model = load(EXAMPLES / name / f"{name}.jin")
        targets = [
            unicodedata.normalize("NFKC", node.targets[0].id)
            for node in ast.parse(generate(model).agent_py).body
            if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name)
        ]
        checkers = sum(1 for c in model.circles if c.flow is not None and c.flow.exit is not None)
        assert len(targets) == len(set(targets)) == len(model.circles) + checkers


