@pytest.mark.parametrize("text", NASTY)
def test_py_literal_roundtrips(text: str) -> None:
    literal = py_literal(text)
    assert literal.startswith('"') and literal.endswith('"')
    assert "\n" not in literal and "\r" not in literal
    assert ast.literal_eval(literal) == text
    literal.encode("utf-8")  # 生成物を UTF-8 で書ける（孤立サロゲートが生で残らない）
    assert "\u2028" not in literal and "\u2029" not in literal


def _body_kinds(agent_py: str) -> set[str]:
    return {type(node).__name__ for node in ast.parse(agent_py).body}


@pytest.mark.parametrize(
    "source_name",
    [
        "x\nimport os; os.system('id')\n#.jin",  # F-S-P2-001 の実測入力
        'x"\nimport os\n#.jin',
        "a\u2028import os\u2029#.jin",
        "bad\udcff.jin",
    ],
)
def test_source_name_cannot_inject_statements(source_name: str) -> None:
    """`.jin` のファイル名（`source_name`）はヘッダのコメントに載る。改行入りでも文にならない。"""
    project = generate(load(EXAMPLES / "pipeline" / "pipeline.jin"), source_name=source_name)
    allowed = {"ImportFrom", "Import", "Assign", "FunctionDef", "ClassDef"}
    assert _body_kinds(project.agent_py) <= allowed
    project.agent_py.encode("utf-8")
    head = project.agent_py.split("\n\n", 1)[0]
    assert all(line.startswith("#") for line in head.splitlines())
    code_lines = [line for line in project.agent_py.splitlines() if not line.startswith("#")]
    assert "os.system" not in "\n".join(code_lines)


def test_jin_strings_cannot_inject_statements() -> None:
    """name / description / rune / equals に Python を仕込んでも、生成物は代入と import だけで構成される。"""
    injected = '") ; import os ; os.system("id") #'
    model = minimal(
        description=injected,
        instruction={"rune": f"{injected}\n{injected}"},
        state=[{"name": "k", "type": "str", "out": True}],
    )
    project = generate(model, source_name="x\nimport os\n#.jin")
    module = ast.parse(project.agent_py)
    kinds = {type(node).__name__ for node in module.body}
    assert kinds <= {"ImportFrom", "Assign"}, kinds
    assert all(
        isinstance(node, ast.ImportFrom) or isinstance(node.value, ast.Call) for node in module.body
    )
    # description がそのまま値として残っている（文として実行されていない）
    call = next(node.value for node in module.body if isinstance(node, ast.Assign))
    values = {kw.arg: kw.value for kw in call.keywords}
    assert ast.literal_eval(values["description"]) == injected


