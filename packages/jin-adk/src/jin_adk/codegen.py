def _py_literal(value: bool | float | str) -> str:
    """`flow.exit.equals` を Python のリテラルにする。

    `bool` は `int` の派生なので**先に**見る（`True` が `1` になると比較が変わる）。
    """
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str):
        return _py_string(value)
    return repr(value)


def _py_list(items: list[str]) -> str:
    """複数要素は 1 行 1 要素で並べる（差分が読みやすく、順序が目で追える）。"""
    if not items:
        return "[]"
    body = "".join(f"        {item},\n" for item in items)
    return f"[\n{body}    ]"


def _render_user_imports(order: list[str], local_name: dict[str, str]) -> str:
    """`ref` の import 文をモジュールごとにまとめる（要件書 §3.2 の形）。

    モジュールは first-appearance 順、その中の名前も first-appearance 順。
    別名が付いたものだけ `as` を書く。
    """
    grouped: dict[str, list[str]] = {}
    for ref in order:
        module, _, name = ref.partition(":")
        local = local_name[ref]
        clause = name if local == name else f"{name} as {local}"
        grouped.setdefault(module, [])
        if clause not in grouped[module]:
            grouped[module].append(clause)
    return "\n".join(
        f"from {module} import {', '.join(names)}" for module, names in grouped.items()
    )


